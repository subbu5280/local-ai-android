/**
 * M9: cross-implementation test vectors for the backup cryptography.
 *
 * The production container code (src/backup/format.ts) writes a real backup file using Node's crypto (OpenSSL) behind
 * the AiCrypto interface, with FIXED test-only salt and nonce prefix (production always uses SecureRandom). The file
 * and the expected values are stored under android/app/src/test/resources/backup/, where the Kotlin tests
 * (BackupCryptoChecks: JVM unit tests and on-device instrumentation tests) decrypt them with the production
 * BackupCrypto class, and produce the same ciphertexts from the same inputs.
 *
 * This test regenerates the vectors and fails if they differ from the stored ones (so a format change can't slip by);
 * set UPDATE_CRYPTO_VECTORS=1 to rewrite them deliberately.
 * Note: this file proves Node ↔ format compatibility only. The Kotlin implementation is proven by the Kotlin tests.
 */
jest.mock('@dr.pogodin/react-native-fs', () => require('../testUtils/fakeBackupEnv').fakeFs());

import { NativeModules } from 'react-native';
import * as RNFS from '@dr.pogodin/react-native-fs';
import { ContainerWriter, aadFor, headerText, nonceFor, openContainer, readChunks } from '../src/backup/format';
import { fakeCrypto, fsState } from '../testUtils/fakeBackupEnv';

const node = (name: string) => (globalThis as any).process.getBuiltinModule(name);
const fs = node('fs'), path = node('path');
const Buf = (globalThis as any).Buffer;
const DIR = 'android/app/src/test/resources/backup';
const b64 = (s: string) => Buf.from(s, 'utf8').toString('base64');

export const PASSWORD = 'pässwörd తెలుగు 🔐 backup';
const SALT = '00112233445566778899aabbccddeeff'; // test-only, fixed
const NONCE_PREFIX = 'f0e1d2c3b4a59687'; // test-only, fixed
const CHUNKS = ['{"type":"manifest","note":"first chunk"}\n', '', 'తెలుగు हिन्दी தமிழ் ಕನ್ನಡ മലയാളം 🔐\n', 'x'.repeat(1000), 'last chunk'];

async function generate(): Promise<{ props: string; container: string }> {
  const crypto = fakeCrypto();
  const fixed = [SALT, NONCE_PREFIX];
  NativeModules.AiCrypto = { ...crypto, randomHex: async (n: number) => { const v = fixed.shift()!; expect(v.length).toBe(n * 2); return v; } };
  await RNFS.mkdir(`${fsState.root}/v`);
  const file = `${fsState.root}/v/c.txt`;
  const w = await ContainerWriter.create(file, PASSWORD, 200_000);
  for (const c of CHUNKS) await w.add(c);
  await w.finish();
  w.close();
  const container = fs.readFileSync(file, 'utf8');

  // Independent values for the Kotlin tests: the key (PBKDF2 at the production 600,000 iterations) and single seals.
  const nodeCrypto = node('crypto');
  const key600 = nodeCrypto.pbkdf2Sync(Buf.from(PASSWORD, 'utf8'), Buf.from(SALT, 'hex'), 600_000, 32, 'sha256').toString('hex');
  const key200 = nodeCrypto.pbkdf2Sync(Buf.from(PASSWORD, 'utf8'), Buf.from(SALT, 'hex'), 200_000, 32, 'sha256').toString('hex');
  const lines = [
    '# Generated by __tests__/cryptoVectors.test.ts (Node/OpenSSL + src/backup/format.ts). TEST-ONLY salt and nonces.',
    `password.b64=${b64(PASSWORD)}`, `salt=${SALT}`, `noncePrefix=${NONCE_PREFIX}`,
    `key.600000=${key600}`, `key.200000=${key200}`,
    `chunks.count=${CHUNKS.length}`, ...CHUNKS.map((c, i) => `chunks.${i}.b64=${b64(c)}`),
  ];
  // A few single seals with the 200,000-iteration key.
  const h = await crypto.deriveKey(PASSWORD, SALT, 200_000);
  const header = headerText({ format: 1, cipher: 'AES-256-GCM', kdf: { name: 'PBKDF2-HMAC-SHA256', iterations: 200_000, salt: SALT }, nonce: NONCE_PREFIX });
  for (const [i, plain] of ['', 'hello', 'తెలుగు 🔐'].entries()) {
    const nonce = nonceFor(NONCE_PREFIX, i), aad = aadFor(header, i, i === 2);
    lines.push(`gcm.${i}.nonce=${nonce}`, `gcm.${i}.aad.b64=${b64(aad)}`, `gcm.${i}.plain.b64=${b64(plain)}`, `gcm.${i}.sealed=${await crypto.seal(h, nonce, aad, plain)}`);
  }
  return { props: `${lines.join('\n')}\n`, container };
}

test('a backup written by the release app on an Android emulator (Kotlin BackupCrypto) is read by the TypeScript reader on Node/OpenSSL', async () => {
  // __tests__/fixtures/android-emulator-backup-v1.txt was created by scripts/emulator-backup-e2e.mjs (Android 17, x86_64
  // emulator, release APK; contents: the three default agents; password "correct horse battery").
  NativeModules.AiCrypto = fakeCrypto();
  const file = '__tests__/fixtures/android-emulator-backup-v1.txt';
  const opened = await openContainer(file, 'correct horse battery');
  expect(opened.header.kdf).toMatchObject({ name: 'PBKDF2-HMAC-SHA256', iterations: 600_000 });
  const records: any[] = [];
  await readChunks(file, opened, async t => { t.split('\n').filter(Boolean).forEach(l => records.push(JSON.parse(l))); });
  expect(records[0]).toMatchObject({ type: 'manifest', payloadVersion: 1, appSchema: 9 });
  expect(records.filter(r => r.type === 'row' && r.table === 'agents').map(r => r.row.name).sort()).toEqual(['Calculator and clock', 'Document assistant', 'Notes writer']);
  expect(records[records.length - 1]).toEqual({ type: 'end', records: 3 });
  await expect(openContainer(file, 'wrong password').then(o => readChunks(file, o, async () => undefined))).rejects.toMatchObject({ code: 'auth_failed' });
}, 30_000);

test('the stored cross-implementation vectors match what the production format code produces', async () => {
  const { props, container } = await generate();
  // The generated container must also read back through the production reader.
  const file = `${fsState.root}/v/c.txt`;
  NativeModules.AiCrypto = fakeCrypto();
  const opened = await openContainer(file, PASSWORD);
  const got: string[] = [];
  await readChunks(file, opened, async t => { got.push(t); });
  expect(got).toEqual(CHUNKS);

  const propsFile = path.join(DIR, 'vectors.properties'), containerFile = path.join(DIR, 'container-v1.txt');
  if ((globalThis as any).process.env.UPDATE_CRYPTO_VECTORS === '1' || !fs.existsSync(propsFile)) {
    fs.mkdirSync(DIR, { recursive: true });
    fs.writeFileSync(propsFile, props);
    fs.writeFileSync(containerFile, container);
  }
  expect(fs.readFileSync(propsFile, 'utf8')).toBe(props);
  expect(fs.readFileSync(containerFile, 'utf8')).toBe(container);
});
